// Bundle the pure mobile reducers without a second implementation of their rules.
const fs = require('fs');
const path = require('path');
const ts = require('../mobile/node_modules/typescript');
const root = path.resolve(__dirname, '../mobile/src');
const modules = {};
function add(name) {
  if (modules[name]) return;
  const source = fs.readFileSync(path.join(root, name + '.ts'), 'utf8');
  const js = ts.transpileModule(source, { compilerOptions: {
    target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS,
  }}).outputText;
  modules[name] = js;
  for (const match of js.matchAll(/require\("([^"]+)"\)/g)) {
    if (!match[1].startsWith('.')) throw new Error('Reducer has a runtime dependency: ' + match[1]);
    add(path.posix.normalize(path.posix.join(path.posix.dirname(name), match[1])));
  }
}
add('state/reducer'); add('state/tasksReducer'); add('state/profileReducer');
const output = `// Generated by node scripts/build-reporting.cjs. Do not edit.\nconst sources = ${JSON.stringify(modules)};\n` + `
const cache = {};
function load(name) {
  if (cache[name]) return cache[name].exports;
  const module = cache[name] = {exports:{}};
  new Function('require', 'module', 'exports', sources[name])(
    relative => load(require('path').posix.normalize(require('path').posix.join(require('path').posix.dirname(name), relative))), module, module.exports);
  return module.exports;
}
const {withEvent} = load('state/eventClock');
const {reducer} = load('state/reducer');
const {initialHouseholdState} = load('data/seed');
const {tasksReducer, initialTasksState} = load('state/tasksReducer');
const {profileReducer} = load('state/profileReducer');
const {DEFAULT_PROFILE} = load('state/profile');
let input = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', chunk => input += chunk);
process.stdin.on('end', () => {
  try {
    const {stream, state, events} = JSON.parse(input);
    const reduce = stream === 'grocery' ? reducer : stream === 'tasks' ? tasksReducer : profileReducer;
    let result = state ?? (stream === 'grocery' ? initialHouseholdState : stream === 'tasks' ? initialTasksState : DEFAULT_PROFILE);
    for (const event of events) result = withEvent(event.at, event.id, () => reduce(result, event.body));
    process.stdout.write(JSON.stringify(result));
  } catch (error) { process.stderr.write(String(error)); process.exitCode = 1; }
});
`;
const target = path.resolve(__dirname, '../backend/app/reporting/replay.cjs');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Reporting reducers are stale; run node scripts/build-reporting.cjs');
} else fs.writeFileSync(target, output);
